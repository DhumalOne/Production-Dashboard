// Writes deploy/.env for the production server: settings from ../deploy.env, the Claude key from
// ../apps/web/.env.local, and newly generated passwords and sign-in keys. Existing secrets in deploy/.env are
// kept, so running it again only fills what is missing.   node deploy/make-env.mjs
import { createHmac, randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const read = (file) => existsSync(file)
  ? Object.fromEntries(readFileSync(file, "utf8").split(/\r?\n/).filter((l) => /^[A-Z_]+=/.test(l))
      .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).trim().replace(/^"(.*)"$/, "$1")]))
  : {};

const deploy = read(join(here, "..", "deploy.env"));
const web = read(join(here, "..", "apps", "web", ".env.local"));
const current = read(join(here, ".env"));

const secret = (bytes = 32) => randomBytes(bytes).toString("base64url");
const b64 = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");
/** HS256 JWT, as the sign-in service expects for the anon and service_role keys. */
function jwt(payload, key) {
  const head = b64({ alg: "HS256", typ: "JWT" }) + "." + b64(payload);
  return head + "." + createHmac("sha256", key).update(head).digest("base64url");
}

const JWT_SECRET = current.JWT_SECRET || secret(48);
const iat = Math.floor(Date.now() / 1000);
const exp = iat + 10 * 365 * 24 * 3600;

const env = {
  DOMAIN: current.DOMAIN || "prod.dhumal.com",
  POSTGRES_PASSWORD: current.POSTGRES_PASSWORD || secret(),
  JWT_SECRET,
  ANON_KEY: current.ANON_KEY || jwt({ role: "anon", iss: "supabase", iat, exp }, JWT_SECRET),
  SERVICE_ROLE_KEY: current.SERVICE_ROLE_KEY || jwt({ role: "service_role", iss: "supabase", iat, exp }, JWT_SECRET),
  DASH_WEB_PASSWORD: current.DASH_WEB_PASSWORD || secret(),
  DASH_INGEST_PASSWORD: current.DASH_INGEST_PASSWORD || secret(),
  DASH_AI_PASSWORD: current.DASH_AI_PASSWORD || secret(),
  INGEST_API_KEYS: current.INGEST_API_KEYS || secret(32),
  GOOGLE_CLIENT_ID: deploy.GOOGLE_CLIENT_ID,
  GOOGLE_CLIENT_SECRET: deploy.GOOGLE_CLIENT_SECRET,
  GOOGLE_WORKSPACE_DOMAIN: "dhumal.com",
  ALLOWED_EMAILS: deploy.ALLOWED_EMAILS || web.ALLOWED_EMAILS,
  ANTHROPIC_API_KEY: web.ANTHROPIC_API_KEY,
  SMTP_HOST: deploy.SMTP_HOST,
  SMTP_PORT: deploy.SMTP_PORT,
  SMTP_USER: deploy.SMTP_USER,
  SMTP_PASS: deploy.SMTP_PASS,
  SMTP_SENDER_EMAIL: deploy.SMTP_SENDER_EMAIL,
  SMTP_SENDER_NAME: deploy.SMTP_SENDER_NAME,
  EMAIL_CODES: deploy.SMTP_HOST ? "on" : "off",
  BACKUP_UPLOAD_URL: current.BACKUP_UPLOAD_URL || "",
};

const missing = ["GOOGLE_CLIENT_ID", "GOOGLE_CLIENT_SECRET", "ALLOWED_EMAILS"].filter((k) => !env[k]);
if (missing.length) {
  console.error(`Fill these in deploy.env first: ${missing.join(", ")}`);
  process.exit(1);
}
writeFileSync(join(here, ".env"),
  "# Production server settings and secrets. Generated by make-env.mjs. Never commit or share.\n" +
  // Quoted when needed, so both Docker Compose and the shell scripts (`source .env`) read it the same way.
  Object.entries(env).map(([k, v]) => `${k}=${/^[\w.@,:/+=-]*$/.test(v ?? "") ? v ?? "" : `"${v}"`}`).join("\n") + "\n");
console.log(`Wrote deploy/.env for ${env.DOMAIN} (${Object.keys(env).length} settings; secrets not shown).`);
if (!env.ANTHROPIC_API_KEY) console.log("note: no ANTHROPIC_API_KEY, so the AI box and briefing will be off.");
if (env.EMAIL_CODES === "off") console.log("note: no SMTP server, so sign-in is Google only.");
